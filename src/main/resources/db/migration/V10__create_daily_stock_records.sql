-- 정제 결과의 원본 단위 일별 수불과 계산용 상품 일별 수불.
-- 수량은 계산 과정의 소수를 잃지 않도록 NUMERIC(18, 3)으로 저장한다.
CREATE TABLE daily_stock_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_file_id BIGINT NOT NULL REFERENCES upload_files (id),
    inventory_unit_id BIGINT NOT NULL REFERENCES inventory_units (id),
    stock_date DATE NOT NULL,
    opening_qty NUMERIC(18, 3) NOT NULL,
    inbound_qty NUMERIC(18, 3) NOT NULL,
    outbound_qty NUMERIC(18, 3) NOT NULL,
    adjustment_qty NUMERIC(18, 3) NOT NULL,
    closing_qty NUMERIC(18, 3) NOT NULL,
    -- 정제 계약에서 값 목록이 확정되기 전까지 원문 상태를 보존한다.
    quality_status VARCHAR(20),
    source_sheet VARCHAR(255) NOT NULL,
    source_row INTEGER NOT NULL CHECK (source_row > 0),
    CONSTRAINT uk_daily_stock_records_source
        UNIQUE (upload_file_id, inventory_unit_id, stock_date)
);

CREATE INDEX idx_daily_stock_records_inventory_date
    ON daily_stock_records (inventory_unit_id, stock_date);
CREATE INDEX idx_daily_stock_records_upload
    ON daily_stock_records (upload_file_id);

CREATE TABLE product_daily_stocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id),
    upload_file_id BIGINT NOT NULL REFERENCES upload_files (id),
    stock_date DATE NOT NULL,
    opening_qty NUMERIC(18, 3) NOT NULL,
    inbound_qty NUMERIC(18, 3) NOT NULL,
    outbound_qty NUMERIC(18, 3) NOT NULL,
    adjustment_qty NUMERIC(18, 3) NOT NULL,
    closing_qty NUMERIC(18, 3) NOT NULL,
    is_valid_observation BOOLEAN NOT NULL,
    observation_note VARCHAR(255),
    CONSTRAINT uk_product_daily_stocks_source
        UNIQUE (upload_file_id, product_id, stock_date)
);

CREATE INDEX idx_product_daily_stocks_product_date
    ON product_daily_stocks (product_id, stock_date);
CREATE INDEX idx_product_daily_stocks_upload
    ON product_daily_stocks (upload_file_id);
