-- 계산 재현에 필요한 원본 파일, 시나리오, 백테스트, AI 인사이트 이력.
CREATE TABLE run_source_files (
    run_id BIGINT NOT NULL REFERENCES calculation_runs (id) ON DELETE CASCADE,
    upload_file_id BIGINT NOT NULL REFERENCES upload_files (id),
    PRIMARY KEY (run_id, upload_file_id)
);

CREATE INDEX idx_run_source_files_upload ON run_source_files (upload_file_id);

CREATE TABLE scenario_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id BIGINT NOT NULL REFERENCES calculation_results (id) ON DELETE CASCADE,
    scenario_type VARCHAR(10) NOT NULL
        CHECK (scenario_type IN ('P80', 'P100', 'P120', 'CUSTOM')),
    scenario_qty BIGINT NOT NULL CHECK (scenario_qty >= 0),
    is_duplicate BOOLEAN NOT NULL DEFAULT FALSE,
    expected_depletion_on DATE,
    expected_ending_stock NUMERIC(18, 3) NOT NULL,
    unmet_demand_qty NUMERIC(18, 3) NOT NULL CHECK (unmet_demand_qty >= 0),
    post_arrival_risk NUMERIC(5, 4) CHECK (post_arrival_risk BETWEEN 0 AND 1),
    daily_projection JSONB NOT NULL,
    actual_ending_stock NUMERIC(18, 3),
    actual_stockout BOOLEAN,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_scenario_results_type UNIQUE (result_id, scenario_type)
);

CREATE INDEX idx_scenario_results_result ON scenario_results (result_id);

CREATE TABLE backtest_metrics (
    result_id BIGINT PRIMARY KEY REFERENCES calculation_results (id) ON DELETE CASCADE,
    actual_outbound_qty NUMERIC(18, 3) NOT NULL,
    absolute_error NUMERIC(18, 3) NOT NULL CHECK (absolute_error >= 0),
    cover_success BOOLEAN NOT NULL,
    ending_stock_qty NUMERIC(18, 3) NOT NULL,
    excess_flag BOOLEAN NOT NULL,
    shortage_days INTEGER NOT NULL CHECK (shortage_days >= 0),
    average_stock_qty NUMERIC(18, 3) NOT NULL,
    baseline_shortage_days INTEGER CHECK (baseline_shortage_days >= 0),
    baseline_average_stock_qty NUMERIC(18, 3)
);

-- AI 계약의 mode/status 값은 아직 합의 중이므로 문자열을 그대로 보존하고,
-- 숫자 범위와 result당 1행이라는 안정된 조건만 DB에서 강제한다.
CREATE TABLE ai_explanations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id BIGINT NOT NULL REFERENCES calculation_results (id) ON DELETE CASCADE,
    mode VARCHAR(20) NOT NULL,
    output_path VARCHAR(100),
    status VARCHAR(20) NOT NULL,
    request_payload JSONB NOT NULL,
    raw_text TEXT,
    validation_passed BOOLEAN NOT NULL,
    inserted_values JSONB,
    rendered_text TEXT,
    reason_code VARCHAR(50),
    model_name VARCHAR(100),
    versions JSONB NOT NULL,
    input_tokens INTEGER CHECK (input_tokens >= 0),
    output_tokens INTEGER CHECK (output_tokens >= 0),
    latency_ms INTEGER CHECK (latency_ms >= 0),
    cost_usd NUMERIC(12, 6) CHECK (cost_usd >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_explanations_result UNIQUE (result_id)
);
