-- 기존 원본·발주·배정은 삭제하지 않는다. 논리적 입고 사건은 revision과 독립적이다.
ALTER TABLE products ADD CONSTRAINT uq_matching_product_owner UNIQUE (id, user_id);
ALTER TABLE warehouses ADD CONSTRAINT uq_matching_warehouse_owner UNIQUE (id, user_id);
ALTER TABLE upload_files ADD CONSTRAINT uq_matching_upload_warehouse UNIQUE (id, warehouse_id);
ALTER TABLE planned_receipts ADD CONSTRAINT uq_matching_receipt_scope UNIQUE (id, warehouse_id, product_id);

CREATE TABLE receipt_matching_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    stock_date DATE NOT NULL,
    quantity BIGINT NOT NULL CHECK (quantity >= 0),
    valid_observation BOOLEAN NOT NULL,
    source_upload_file_id BIGINT NOT NULL,
    review_required BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (warehouse_id, product_id, stock_date),
    UNIQUE (id, warehouse_id, product_id),
    FOREIGN KEY (product_id, user_id) REFERENCES products (id, user_id),
    FOREIGN KEY (warehouse_id, user_id) REFERENCES warehouses (id, user_id),
    FOREIGN KEY (source_upload_file_id, warehouse_id) REFERENCES upload_files (id, warehouse_id)
);

CREATE TABLE receipt_matching_allocations (
    receipt_id BIGINT PRIMARY KEY,
    event_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    sku_name VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (receipt_id, warehouse_id, product_id) REFERENCES planned_receipts (id, warehouse_id, product_id),
    FOREIGN KEY (event_id, warehouse_id, product_id) REFERENCES receipt_matching_events (id, warehouse_id, product_id)
);
CREATE INDEX idx_receipt_matching_allocations_event ON receipt_matching_allocations (event_id);

