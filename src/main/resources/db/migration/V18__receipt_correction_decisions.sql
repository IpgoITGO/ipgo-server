ALTER TABLE receipt_matching_events ADD COLUMN confirmed_source_fingerprint VARCHAR(64);
ALTER TABLE receipt_matching_events ADD COLUMN correction_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE receipt_matching_events ADD COLUMN last_decision_id VARCHAR(36);

CREATE TABLE receipt_correction_decisions (
    id VARCHAR(36) PRIMARY KEY,
    event_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    source_upload_file_id BIGINT NOT NULL,
    source_fingerprint VARCHAR(64) NOT NULL,
    action VARCHAR(12) NOT NULL CHECK (action IN ('KEEP','REPLACE')),
    reason VARCHAR(500) NOT NULL,
    idempotency_key VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    previous_version VARCHAR(64) NOT NULL,
    snapshot JSONB NOT NULL,
    response JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id,idempotency_key),
    UNIQUE(id,event_id,warehouse_id,product_id),
    FOREIGN KEY(event_id,warehouse_id,product_id) REFERENCES receipt_matching_events(id,warehouse_id,product_id),
    FOREIGN KEY(warehouse_id,user_id) REFERENCES warehouses(id,user_id),
    FOREIGN KEY(source_upload_file_id,warehouse_id) REFERENCES upload_files(id,warehouse_id)
);
CREATE INDEX idx_receipt_correction_decisions_event ON receipt_correction_decisions(event_id,created_at,id);

CREATE TABLE receipt_allocation_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    receipt_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL CHECK(quantity > 0),
    sku_name VARCHAR(200) NOT NULL,
    received_on DATE NOT NULL,
    action VARCHAR(12) NOT NULL CHECK(action IN ('BASELINE','ASSIGN','RELEASE')),
    decision_id VARCHAR(36),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(event_id,warehouse_id,product_id) REFERENCES receipt_matching_events(id,warehouse_id,product_id),
    FOREIGN KEY(decision_id,event_id,warehouse_id,product_id) REFERENCES receipt_correction_decisions(id,event_id,warehouse_id,product_id),
    FOREIGN KEY(receipt_id,warehouse_id,product_id) REFERENCES planned_receipts(id,warehouse_id,product_id)
);
CREATE INDEX idx_receipt_allocation_history_event ON receipt_allocation_history(event_id,id);
INSERT INTO receipt_allocation_history(event_id,receipt_id,warehouse_id,product_id,quantity,sku_name,received_on,action,created_at)
SELECT a.event_id,a.receipt_id,a.warehouse_id,a.product_id,a.quantity,a.sku_name,e.stock_date,'BASELINE',a.created_at
FROM receipt_matching_allocations a JOIN receipt_matching_events e ON e.id=a.event_id;

