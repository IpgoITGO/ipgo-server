    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='ipgo_ai_service_reader') THEN
        REVOKE ALL ON push_subscriptions, notification_settings FROM ipgo_ai_service_reader;
    END IF;
