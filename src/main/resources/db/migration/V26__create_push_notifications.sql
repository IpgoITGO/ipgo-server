-- #190 Web Push 알림 1단계: 브라우저 구독과 알림 설정. 발송 기록은 보내기 단계에서 따로 추가한다.
-- 두 표 모두 새 표라 기존 데이터는 바뀌지 않고, 되돌릴 때는 두 표를 지우면 된다(다른 표가 참조하지 않는다).

-- 브라우저(기기)마다 1행. endpoint는 브라우저 회사 푸시 서버 주소라 길고 비밀에 가까워서
-- 응답 · 로그에 내보내지 않고, 같은 브라우저인지는 SHA-256 hash로 찾는다.
CREATE TABLE push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    endpoint_hash CHAR(64) NOT NULL UNIQUE,
    endpoint VARCHAR(2048) NOT NULL,
    p256dh VARCHAR(200) NOT NULL,
    auth_secret VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_push_subscriptions_user ON push_subscriptions (user_id, active);

-- 알림 종류 × 받는 방법마다 1행. 행이 없으면 꺼짐(기본값)이다. 메일 알림(후속)도 channel EMAIL로 같은 표를 쓴다.
-- send_hour는 time_zone 기준 정시(0~23시)다.
CREATE TABLE notification_settings (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind VARCHAR(40) NOT NULL CHECK (kind IN ('REPLENISHMENT_NEEDED')),
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('PUSH', 'EMAIL')),
    enabled BOOLEAN NOT NULL,
    send_hour SMALLINT NOT NULL CHECK (send_hour BETWEEN 0 AND 23),
    time_zone VARCHAR(64) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, kind, channel)
);

-- PostgreSQL 전용
