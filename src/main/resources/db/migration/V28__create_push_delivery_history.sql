-- #190 사용자 업무일 요약과 기기별 상태. 구독 endpoint/키/payload 원문은 복제하지 않는다.
CREATE TABLE push_daily_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind VARCHAR(40) NOT NULL DEFAULT 'REPLENISHMENT_NEEDED',
    business_date DATE NOT NULL,
    time_zone VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(user_id, kind, business_date)
);
CREATE TABLE push_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    summary_id BIGINT NOT NULL REFERENCES push_daily_summaries(id) ON DELETE CASCADE,
    subscription_id BIGINT NOT NULL,
    subscription_updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    state VARCHAR(20) NOT NULL CHECK (state IN ('PENDING','SENDING','SENT','RETRY','FAILED','EXPIRED','UNKNOWN','CANCELED')),
    attempts SMALLINT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    provider_status SMALLINT,
    UNIQUE(summary_id, subscription_id)
);
CREATE INDEX idx_push_deliveries_due ON push_deliveries(state, next_attempt_at);
-- PostgreSQL role permissions
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='ipgo_ai_reader') THEN
        REVOKE ALL ON push_daily_summaries, push_deliveries FROM ipgo_ai_reader;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='ipgo_ai_service_reader') THEN
        REVOKE ALL ON push_daily_summaries, push_deliveries FROM ipgo_ai_service_reader;
    END IF;
END $$;
