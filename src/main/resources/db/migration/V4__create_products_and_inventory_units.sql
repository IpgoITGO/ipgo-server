-- 상품 자동 등록(BE-05)에 필요한 창고·상품·재고관리단위 표. 이름과 칸은 최종 ERD를 따른다.
CREATE TABLE warehouses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    name VARCHAR(100) NOT NULL,
    workplace_code VARCHAR(50),
    default_lead_time_days INTEGER CHECK (default_lead_time_days > 0),
    default_review_cycle_days INTEGER CHECK (default_review_cycle_days > 0),
    default_order_unit_qty BIGINT CHECK (default_order_unit_qty > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 창고 코드가 없는 창고는 여러 개여도 된다 (NULL은 중복 검사에서 빠진다).
    CONSTRAINT uk_warehouses_user_code UNIQUE (user_id, workplace_code)
);

-- 바코드 1개 = 상품 1행. 업로드에 안 나왔다고 비활성화하지 않으므로 is_active는 셀러만 바꾼다.
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    sku_barcode VARCHAR(100) NOT NULL,
    sku_name VARCHAR(200) NOT NULL,
    unit_cost NUMERIC(18, 2) CHECK (unit_cost >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    explanation_mode VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_products_user_barcode UNIQUE (user_id, sku_barcode)
);

-- 재고관리단위(LOT) 1건 = 같은 창고의 sku_mixed_id + 입고일. 같은 sku_mixed_id라도 입고일이 다르면 다른 행이다.
CREATE TABLE inventory_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    source_inventory_key VARCHAR(100) NOT NULL,
    received_on DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_inventory_units_source UNIQUE (warehouse_id, source_inventory_key, received_on)
);

CREATE INDEX idx_inventory_units_product ON inventory_units (product_id);
