-- 수불부 업로드 기록. 파일 1개 = 1행. 같은 기간을 덮어쓰면 revision_no를 올려 새 행을 만들고 이전 행은 이력으로 남긴다.
CREATE TABLE upload_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    original_name VARCHAR(255) NOT NULL,
    storage_key TEXT NOT NULL,
    file_hash CHAR(64) NOT NULL,
    revision_no INTEGER NOT NULL CHECK (revision_no > 0),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    -- 여러 파일을 한 번에 올릴 때의 묶음 번호. 묶음 방식은 아직 정하지 않았다.
    job_id VARCHAR(100),
    validation_report JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_upload_files_period CHECK (period_start <= period_end),
    CONSTRAINT uk_upload_files_revision UNIQUE (warehouse_id, period_start, revision_no)
);
