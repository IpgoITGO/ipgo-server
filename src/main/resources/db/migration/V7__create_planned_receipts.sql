-- 기존 발주 물량(BE-07). 이미 발주했지만 아직 도착하지 않은 물량이다. 이름과 칸은 최종 ERD를 따른다.
-- 취소해도 행을 지우지 않고 CANCELLED로 남긴다.
CREATE TABLE planned_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    expected_on DATE,
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    received_on DATE,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PENDING', 'RECEIVED', 'OVERDUE', 'NO_DATE', 'CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_planned_receipts_warehouse ON planned_receipts (warehouse_id);
CREATE INDEX idx_planned_receipts_product ON planned_receipts (product_id);
