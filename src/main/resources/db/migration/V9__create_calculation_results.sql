-- 계산 실행과 상품별 계산 결과(BE-08 · BE-11). 이름과 칸은 최종 ERD를 따른다.
-- 엔진 연동 전에는 대시보드(D1) · SKU 상세(K1)가 이 표를 읽기만 하고, 값은 계산 연동(#27)에서 채운다.
CREATE TABLE calculation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    run_type VARCHAR(20) NOT NULL,
    as_of_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    job_id VARCHAR(100),
    engine_version VARCHAR(50) NOT NULL,
    policy_version VARCHAR(50),
    selection_snapshot JSONB NOT NULL,
    error_message TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_calculation_runs_warehouse ON calculation_runs (warehouse_id, id);

CREATE TABLE calculation_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES calculation_runs (id),
    product_id BIGINT NOT NULL REFERENCES products (id),
    origin_date DATE NOT NULL,
    start_date DATE NOT NULL,
    method VARCHAR(10),
    method_reason VARCHAR(30),
    multiplier NUMERIC(5, 3) NOT NULL,
    horizon_days INTEGER NOT NULL,
    start_stock_qty NUMERIC(18, 3),
    planned_receipt_qty BIGINT,
    forecast_outbound_qty NUMERIC(18, 3),
    pre_arrival_unmet_qty NUMERIC(18, 3),
    recommended_qty BIGINT CHECK (recommended_qty >= 0),
    recommended_amount NUMERIC(18, 2) CHECK (recommended_amount >= 0),
    expected_shortage_on DATE,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('OK', 'NOT_NEEDED', 'NOT_CALCULABLE', 'EXCLUDED', 'REUPLOAD_REQUIRED')),
    reason TEXT,
    input_snapshot JSONB NOT NULL,
    pre_arrival_risk NUMERIC(5, 4) CHECK (pre_arrival_risk BETWEEN 0 AND 1),
    risk_sample_size INTEGER,
    risk_basis VARCHAR(10),
    accuracy_grade VARCHAR(10) CHECK (accuracy_grade IN ('HIGH', 'MEDIUM', 'LOW')),
    valid_observation_days INTEGER,
    cover_success_count INTEGER,
    cover_trial_count INTEGER,
    forecast_error_rate NUMERIC(5, 4),
    forecast_range_low NUMERIC(18, 3),
    forecast_range_high NUMERIC(18, 3),
    -- 한 번의 계산에서 상품마다 결과는 1개다.
    CONSTRAINT uk_calculation_results_run_product UNIQUE (run_id, product_id)
);

CREATE INDEX idx_calculation_results_product ON calculation_results (product_id);
